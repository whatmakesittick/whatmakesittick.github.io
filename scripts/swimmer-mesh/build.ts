import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import prettier from 'prettier';
import {
  BONE_COUNT,
  type SlotId,
  SLOT_IDS,
  type Triple,
} from '../../explainers/freestyle-swim/src/scene/parts/swimmer/skin/types.ts';
import { shapeCap, strapLoop } from './cap.ts';
import { surfaceReport } from './checks.ts';
import { OUTPUT_PATH, SIMPLIFY_BUDGET } from './config.ts';
import { cutMesh } from './cut.ts';
import { encodeHalfMesh, type HalfMesh } from './encode.ts';
import { prepareBody, type PreparedBody } from './prepare.ts';
import type { Model } from './topology.ts';
import { restJoints, restLengths } from './measure.ts';
import { restSide } from './restpose.ts';
import { stripOrder } from './order.ts';
import { reorderByFirstUse, simplifyBody } from './simplify.ts';
import { capDistance, classifyTriangles, cutPlanes, headWeight, type SlotRules } from './slots.ts';
import { loadSource } from './source.ts';
import { point } from './vec.ts';

const HEADER = '// Generated by scripts/swimmer-mesh/build.ts\n';
const HEAD_WEIGHT_MIN = 0.5;

function verticesOf(
  triangles: readonly number[],
  keep: (triangle: number) => boolean,
): Set<number> {
  const vertices = new Set<number>();
  for (let t = 0; t < triangles.length / 3; t++) {
    if (keep(t)) for (let k = 0; k < 3; k++) vertices.add(triangles[t * 3 + k]);
  }
  return vertices;
}

function shapeHead(
  body: PreparedBody,
  slotOf: SlotId[],
  rules: SlotRules,
): { headTop: number; strap: ReturnType<typeof strapLoop> } {
  const { model } = body;
  const isCap = (t: number): boolean => slotOf[t] === 'cap' || slotOf[t] === 'capStripe';
  const capVertices = verticesOf(model.triangles, isCap);
  const rim = new Set(
    [...verticesOf(model.triangles, (t) => !isCap(t))].filter((v) => capVertices.has(v)),
  );
  const capTriangles = model.triangles.filter((_, i) => isCap(Math.floor(i / 3)));
  shapeCap(model, capTriangles, rim, (v) => capDistance(rules, point(model.positions, v)));
  const headVertices = [
    ...verticesOf(model.triangles, (t) => isCap(t) || slotOf[t] === 'face'),
  ].filter((v) => headWeight(model, v) > HEAD_WEIGHT_MIN);
  const highest = [...capVertices].reduce((best, v) =>
    model.positions[v * 3] > model.positions[best * 3] ? v : best,
  );
  const headTop = point(model.positions, highest) as Triple;
  return { headTop, strap: strapLoop(headVertices, model.positions, body.eye[0]) };
}

function slotsOf(model: Model, rules: SlotRules): Record<SlotId, number[]> {
  const slotOf = classifyTriangles(model, rules);
  return Object.fromEntries(
    SLOT_IDS.map((slot) => [
      slot,
      stripOrder(
        slotOf.flatMap((owner, t) =>
          owner === slot ? model.triangles.slice(t * 3, t * 3 + 3) : [],
        ),
      ),
    ]),
  ) as Record<SlotId, number[]>;
}

function assemble(
  body: PreparedBody,
  model: Model,
  simplified: Record<SlotId, number[]>,
  slotInfo: ReturnType<typeof shapeHead>,
) {
  const { order, slots } = reorderByFirstUse(simplified);
  const positions = new Float64Array(order.length * 3);
  const joints = new Uint8Array(order.length * 4);
  const weights = new Float32Array(order.length * 4);
  order.forEach((vertex, i) => {
    positions.set(model.positions.subarray(vertex * 3, vertex * 3 + 3), i * 3);
    joints.set(model.joints.subarray(vertex * 4, vertex * 4 + 4), i * 4);
    weights.set(model.weights.subarray(vertex * 4, vertex * 4 + 4), i * 4);
  });
  const joint = restJoints(body);
  const right = restSide(model.positions, joint, { ...body.parts, eye: body.eye });
  const neck = body.joint('neck01____head');
  const rest = {
    right,
    neck,
    headTop: slotInfo.headTop,
    eyeRadius: body.eyeRadius,
    strap: slotInfo.strap,
  };
  return { positions, joints, weights, slots, rest } as HalfMesh;
}

function farthestBack(model: Model): number {
  let back = -Infinity;
  for (let v = 0; v < model.positions.length / 3; v++) {
    if (headWeight(model, v) > HEAD_WEIGHT_MIN) back = Math.max(back, model.positions[v * 3 + 1]);
  }
  return back;
}

async function main(): Promise<void> {
  const source = await loadSource();
  const body = prepareBody(source);
  const { model } = body;
  const [hip, knee] = [body.joint('upperleg01.R____head'), body.joint('lowerleg01.R____head')];
  const rules: SlotRules = {
    hip,
    knee,
    hipX: body.hipX,
    eye: body.eye,
    capBack: farthestBack(model),
  };
  const slotOf = classifyTriangles(model, rules);
  const head = shapeHead(body, slotOf, rules);
  const simplified = await simplifyBody(model, slotOf, SIMPLIFY_BUDGET);
  const cut = cutMesh({ ...model, triangles: simplified }, cutPlanes(rules));
  const mesh = assemble(body, cut, slotsOf(cut, rules), head);
  const report = surfaceReport(mesh);
  const encoded = encodeHalfMesh(mesh);
  const text = `${HEADER}import type { EncodedBody } from './decode';\n\nexport const bodyMeshData = ${JSON.stringify(encoded)} as EncodedBody;\n`;
  const formatted = await prettier.format(text, {
    parser: 'typescript',
    ...(await prettier.resolveConfig(OUTPUT_PATH)),
  });
  writeFileSync(resolve(OUTPUT_PATH), formatted);

  const midline = Array.from(
    { length: mesh.positions.length / 3 },
    (_, v) => mesh.positions[v * 3 + 2],
  ).filter((z) => z === 0).length;
  const half = mesh.positions.length / 3;
  console.log(
    'rest',
    JSON.stringify(
      Object.fromEntries(
        Object.entries(restLengths(mesh.rest.right)).map(([k, v]) => [
          k,
          Math.round(v * 1000) / 1000,
        ]),
      ),
    ),
  );
  console.log('holes filled', body.filledHoles, 'straddling', body.straddling);
  console.log('half vertices', half, 'midline', midline, 'full vertices', 2 * half - midline);
  const counts = Object.fromEntries(SLOT_IDS.map((s) => [s, mesh.slots[s].length / 3]));
  const fullTriangles = SLOT_IDS.reduce((sum, s) => sum + counts[s], 0) * 2;
  console.log('slot triangles (half)', JSON.stringify(counts), 'full triangles', fullTriangles);
  console.log('surface', JSON.stringify(report), 'bones', BONE_COUNT);
  console.log(
    'full-res slot triangles',
    JSON.stringify(
      Object.fromEntries(SLOT_IDS.map((s) => [s, slotOf.filter((o) => o === s).length])),
    ),
  );
}

await main();
